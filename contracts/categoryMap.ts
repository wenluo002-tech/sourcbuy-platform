// 查词：精确命中优先；否则取 query 包含的最长映射键（"316不锈钢立柱批发"→"316不锈钢立柱"）
// 返回空数组 = 不干预（该词不在图上或人工判定拿不准）
export function lookupCategories(query: string): string[] {
  const q = query.trim();
  if (!q) return [];
  const exact = CATEGORY_MAP[q];
  if (exact?.length) return exact;
  let best = "";
  for (const k in CATEGORY_MAP) {
    if (k.length > best.length && q.includes(k)) best = k;
  }
  return best ? CATEGORY_MAP[best] : [];
}
