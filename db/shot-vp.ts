import { chromium } from "playwright-core";
const BASE = "http://localhost:3200";
const EMAIL = process.argv[2]; const PASS = "Test1234!";
const login = await fetch(`${BASE}/api/trpc/auth.login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ json: { email: EMAIL, password: PASS } }) });
const cookie = login.headers.get("set-cookie") || "";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: "zh-CN" });
const [pair] = cookie.split(";"); const [k, v] = pair.split("=");
await ctx.addCookies([{ name: k, value: v, url: BASE }]);
const page = await ctx.newPage();
await page.goto(`${BASE}/dashboard`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(2600);
await page.screenshot({ path: "/tmp/m4a-shots/dash_mobile_viewport.png", fullPage: false });
console.log("OK");
await browser.close(); process.exit(0);
