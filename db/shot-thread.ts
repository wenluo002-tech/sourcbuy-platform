import { chromium } from "playwright-core";
const BASE = "http://localhost:3200";
const login = await fetch(`${BASE}/api/trpc/auth.login`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ json: { email: "m4atest1794109068991@test.com", password: "Test1234!" } }) });
const cookie = login.headers.get("set-cookie") || "";
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "zh-CN" });
const [pair] = cookie.split(";"); const [k, v] = pair.split("=");
await ctx.addCookies([{ name: k, value: v, url: BASE }]);
const page = await ctx.newPage();
await page.goto(`${BASE}/buyer?thread=2658191`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(3500);
await page.screenshot({ path: "/tmp/m4a-shots/buyer_thread_replay.png", fullPage: false });
console.log("URL_NOW:", page.url());
await page.goto(`${BASE}/inquiries`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(2200);
await page.screenshot({ path: "/tmp/m4a-shots/inquiries_auth2.png", fullPage: false });
await browser.close(); process.exit(0);
